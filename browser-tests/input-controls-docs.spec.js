test("Input Controls navigation and examples cover form input behavior", async ({ page }) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/docs/index.html#text-input");
  await openComponentGroup(page, "Input Controls");
  const tree = page.locator(".dui-docs-tree");
  await expect(tree.getByRole("treeitem", { name: "Input Controls", exact: true })).toHaveAttribute("aria-level", "2");
  for (const name of ["TextInput", "NumberInput", "Password", "Masked", "DateInput", "TimeInput", "SelectInput", "RadioGroup", "CheckBox", "Switch", "TrackBar", "ProgressBar", "FilePicker", "FileUpload"]) {
    await expect(tree.getByRole("treeitem", { name, exact: true })).toHaveAttribute("aria-level", "3");
  }
  const navigate = async name => {
    await tree.getByRole("treeitem", { name, exact: true }).click();
    await expect(page.getByRole("heading", { name, exact: true, level: 1 })).toBeVisible();
  };
  const validation = page.locator('.dui-example-host').filter({ has: page.getByRole("button", { name: "Validate customer", exact: true }) });
  const customer = validation.locator('[data-dui-control-id="customer"] input');
  await customer.fill("");
  await validation.getByRole("button", { name: "Validate customer" }).click();
  await expect(validation.locator(".dui-example-host__output")).toHaveText("Customer is required");
  await validation.getByRole("button", { name: "Reset customer" }).click();
  await expect(customer).toHaveValue("Ada");
  await navigate("NumberInput");
  await page.getByRole("spinbutton", { name: "Quantity" }).fill("25");
  await page.getByRole("button", { name: "Read numbers" }).click();
  await expect(page.locator(".dui-example-host__output")).toHaveText('{"quantity":20,"price":12.5}');
  await navigate("Password");
  const password = page.locator('[data-dui-control-id="password"] input');
  await expect(password).toHaveAttribute("type", "password");
  await page.getByRole("button", { name: "Show password" }).click();
  await expect(password).toHaveAttribute("type", "text");
  await expect(page.locator(".dui-example-host__output")).toHaveText("Password visible");
  await expect(page.locator('[data-dui-control-id="confirmation"] button')).toHaveCount(0);
  await navigate("Masked");
  await page.getByRole("button", { name: "Read masked values" }).click();
  await expect(page.locator(".dui-example-host__output")).toHaveText('{"phone":"+1 (555) 123-4567","reference":"AB1234","display":"AB-1234"}');
  await navigate("DateInput");
  await expect(page.locator(".dui-doc-status")).toHaveText("experimental");
  await page.getByRole("button", { name: "Open calendar", exact: true }).click();
  const calendar = page.locator(".dui-overlay-root > .dui-date-picker");
  await expect(calendar).toBeVisible();
  await calendar.getByRole("button", { name: "17", exact: true }).click();
  await expect(page.locator(".dui-example-host__output")).toHaveText("Start date: 2026-09-17");
  await page.getByRole("button", { name: "Open date and time picker", exact: true }).click();
  await expect(page.locator(".dui-overlay-root > .dui-date-time-picker:not(.dui-date-picker)")).toBeVisible();
  await navigate("TimeInput");
  await expect(page.locator(".dui-overlay-root > .dui-date-time-picker")).toHaveCount(0);
  const reminder = page.locator('[data-dui-control-id="reminder"]');
  await expect(reminder.locator("input")).toHaveValue("02:30 PM");
  await reminder.getByRole("button", { name: "Focus time" }).click();
  const timePicker = page.locator(".dui-overlay-root > .dui-time-picker");
  await timePicker.locator(".dui-time-picker__wheel").first().getByRole("button", { name: "08", exact: true }).click();
  await timePicker.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(reminder.locator("input")).toHaveValue("02:30 PM");
  await navigate("SelectInput");
  await page.getByRole("button", { name: "Replace choices" }).click();
  await expect(page.locator(".dui-example-host__output").nth(1)).toHaveText("Selected after replacement: (empty)");
  const flagCountry = page.locator('[data-dui-control-id="flagCountry"]');
  const selectedFlag = flagCountry.locator(".dui-dropdown-list__display-image img");
  await expect(flagCountry.getByRole("combobox")).toContainText("France");
  await expect.poll(() => selectedFlag.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
  const initialFlag = await selectedFlag.getAttribute("src");
  await flagCountry.getByRole("button", { name: "Open list", exact: true }).click();
  const countryPopup = page.locator(".dui-overlay-root > .dui-dropdown-list__popup");
  await expect(countryPopup.getByRole("option")).toHaveCount(4);
  await expect.poll(() => countryPopup.locator("img").evaluateAll(images => images.length === 4 && images.every(img => img.complete && img.naturalWidth > 0))).toBe(true);
  await countryPopup.getByPlaceholder("Find country").fill("jap");
  await expect(countryPopup.getByRole("option")).toHaveCount(1);
  await countryPopup.getByRole("option", { name: "Japan", exact: true }).click();
  await expect(countryPopup).toBeHidden();
  await expect(flagCountry.getByRole("combobox")).toContainText("Japan");
  await expect(selectedFlag).not.toHaveAttribute("src", initialFlag);
  await expect(page.locator(".dui-example-host__output").nth(2)).toHaveText("Country code: JP");
  await navigate("RadioGroup");
  await page.getByRole("radiogroup", { name: "Delivery", exact: true }).getByText("Express", { exact: true }).click();
  await expect(page.getByRole("radio", { name: /Express/ })).toBeChecked();
  await expect(page.locator(".dui-example-host__output").first()).toHaveText("Delivery: express");
  await expect(page.getByRole("radio", { name: "Pickup", exact: true })).toBeDisabled();
  const letters = page.getByRole("radiogroup", { name: "Choose one", exact: true });
  await letters.getByText("Guide", { exact: true }).click();
  await expect(letters.getByRole("radio", { name: "A. Guide", exact: true })).toBeChecked();
  await expect(letters.getByRole("radio", { name: "B. Examples", exact: true })).not.toBeChecked();
  const numbers = page.getByRole("radiogroup", { name: "Priority", exact: true });
  await numbers.getByText("Urgent", { exact: true }).click();
  await expect(numbers.getByRole("radio", { name: "4. Urgent", exact: true })).toBeChecked();
  await expect(numbers.getByRole("radio", { name: "3. High", exact: true })).not.toBeChecked();
  await navigate("CheckBox");
  await page.getByRole("checkbox", { name: /Share usage statistics/ }).check();
  await page.getByRole("button", { name: "Read preferences" }).click();
  await expect(page.locator(".dui-example-host__output").first()).toHaveText('{"notifications":true,"analytics":true,"managed":true}');
  await page.locator('.dui-check-letter').filter({ hasText: "Source code" }).click();
  await expect(page.getByRole("checkbox", { name: "C. Source code", exact: true })).toBeChecked();
  await expect(page.getByRole("checkbox", { name: "A. Guide", exact: true })).toBeChecked();
  await page.getByRole("button", { name: "Read selected sections", exact: true }).click();
  await expect(page.locator(".dui-example-host__output").last()).toHaveText('["guide","source"]');
  await page.getByRole("button", { name: "Dark", exact: true }).click();
  await expect(page.locator("body")).toHaveClass(/dui-theme-dark-blue/);
  await page.getByPlaceholder("Find component").fill("masked");
  await expect(tree.getByRole("treeitem", { name: "Components", exact: true })).toBeVisible();
  await expect(tree.getByRole("treeitem", { name: "Input Controls", exact: true })).toBeVisible();
  await expect(tree.getByRole("treeitem", { name: "Masked", exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test("Lab 21 input documentation supports multiple choices, sliders, progress and files", async ({ page }) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/docs/index.html#select-input");
  await openComponentGroup(page, "Input Controls");
  const regions = page.locator('[data-dui-control-id="regions"]');
  await regions.getByRole("button", { name: "Open list", exact: true }).click();
  const popup = page.locator(".dui-overlay-root > .dui-dropdown-list__popup");
  await expect(popup.getByRole("listbox")).toHaveAttribute("aria-multiselectable", "true");
  await popup.getByPlaceholder("Find region").fill("sou");
  await popup.getByRole("option", { name: "South", exact: true }).click();
  await expect(popup).toBeVisible();
  await expect(page.locator(".dui-example-host__output").last()).toHaveText('["north","east","south"]');
  await page.keyboard.press("Escape");
  await regions.getByRole("button", { name: "Remove North", exact: true }).click();
  await expect(page.locator(".dui-example-host__output").last()).toHaveText('["east","south"]');
  await page.getByRole("button", { name: "Clear regions", exact: true }).click();
  await expect(regions.locator(".dui-multi-select-dropdown__token")).toHaveCount(0);
  await expect(page.locator(".dui-example-host__output").last()).toHaveText("[]");

  const navigate = name => page.locator(".dui-docs-tree").getByRole("treeitem", { name, exact: true }).click();
  await navigate("Switch");
  await page.getByText("Send schedule reminders", { exact: true }).click();
  await expect(page.locator('[data-dui-control-id="notify"] input')).toBeChecked();
  await expect(page.locator('[data-dui-control-id="managed"] input')).toBeDisabled();
  await expect(page.locator(".dui-example-host__output")).toHaveText("Notify: true");
  await navigate("TrackBar");
  const quality = page.locator('[data-dui-control-id="quality"] input');
  await quality.press("ArrowRight");
  await expect(quality).toHaveValue("65");
  await quality.press("PageDown");
  await expect(quality).toHaveValue("45");
  await quality.press("End");
  await expect(page.locator(".dui-example-host").filter({has:quality}).locator(".dui-example-host__output")).toHaveText("Quality: 100");
  const vertical = page.locator('[data-dui-control-id="level"] input');
  const bounds = await vertical.boundingBox();
  expect(bounds.height).toBeGreaterThan(bounds.width);
  await vertical.press("ArrowUp");
  await expect(vertical).toHaveValue("45");
  await vertical.press("ArrowDown");
  await expect(page.locator(".dui-example-host").filter({has:vertical}).locator(".dui-example-host__output")).toHaveText("Level: 40");
  await navigate("ProgressBar");
  await expect(page.getByRole("progressbar")).toHaveAttribute("aria-valuenow", "35");
  await page.getByRole("button", { name: "Advance +15", exact: true }).click();
  await expect(page.getByRole("progressbar")).toHaveAttribute("aria-valuenow", "50");
  await page.getByRole("button", { name: "Reset progress", exact: true }).click();
  await expect(page.getByRole("progressbar")).toHaveAttribute("aria-valuenow", "0");
  const workflow = page.locator('[data-dui-control-id="workflowProgress"]');
  const stages = workflow.getByRole("button");
  await expect(stages).toHaveCount(4);
  await expect(stages.nth(1)).toHaveAttribute("aria-current", "step");
  await stages.nth(2).click();
  await expect(stages.nth(2)).toHaveAttribute("aria-current", "step");
  await expect(page.locator(".dui-example-host__output").last()).toHaveText("Stage: Validate (index 2)");
  await stages.nth(2).press("ArrowRight");
  await expect(stages.nth(3)).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(stages.nth(3)).toHaveAttribute("aria-current", "step");
  await expect(page.locator(".dui-example-host__output").last()).toHaveText("Stage: Export (index 3)");
  await navigate("FilePicker");
  const single = page.locator('[data-dui-control-id="attachment"]');
  const multiple = page.locator('[data-dui-control-id="attachments"]');
  const file = { name: "sample.txt", mimeType: "text/plain", buffer: Buffer.from("demo") };
  await single.locator('input[type="file"]').setInputFiles(file);
  await expect(page.locator(".dui-example-host__output")).toContainText('"name":"sample.txt","size":4');
  await single.getByRole("button", { name: "Clear file selection", exact: true }).click();
  await expect(page.locator(".dui-example-host__output")).toHaveText("null");
  await expect(single.getByPlaceholder("No file selected")).toHaveValue("");
  await multiple.locator('input[type="file"]').setInputFiles([file, { ...file, name: "second.txt" }]);
  await expect(page.locator(".dui-example-host__output")).toHaveText('[{"name":"sample.txt","size":4},{"name":"second.txt","size":4}]');
  await multiple.getByRole("button", { name: "Clear file selection", exact: true }).click();
  await expect(page.locator(".dui-example-host__output")).toHaveText("[]");
  expect(errors).toEqual([]);
});

test("input documentation snippets mount and match live model values", async ({ page }) => {
  await page.goto("/browser-tests/recipes.html");
  const results = await page.evaluate(async () => {
    const ui = await import("/src/ui/all.js");
    const { docsCatalog } = await import("/docs/src/docsCatalog.js");
    const pages = docsCatalog.find(group => group.id === "components").groups.find(group => group.id === "input-controls").pages;
    const host = document.querySelector("#root");
    const snapshot = control => control.getEntries ? control.getEntries() : control.value ? control.value.get() :
      typeof control.getSelectedItemIndex === "function" ? { selectedItemIndex: control.getSelectedItemIndex(), items: control.getItems() } :
        (control.getItems?.() ?? []).map(snapshot);
    const results = [];
    for (const doc of pages) {
      for (const [index, example] of doc.examples.entries()) {
        const resultName = doc.id === "text-input" && index === 0 ? "name" : doc.id === "select-input" && index === 0 ? "status" : "example";
        const run = new Function(...Object.keys(ui), "log", `${example.source}\nreturn ${resultName};`);
        const log = { write() {} };
        const values = [];
        for (const factory of [() => example.create({ log, container: host }), () => run(...Object.values(ui), log)]) {
          const control = factory();
          if (!control.mounted) control.mount(host);
          values.push(JSON.stringify(snapshot(control)));
          const children = (control.getItems?.() ?? []).filter(item => typeof item.destroy === "function");
          control.destroy();
          if (host.childElementCount || children.some(child => !child.destroyed)) throw new Error(`Leaked ${doc.id}`);
        }
        results.push({ id: `${doc.id}/${index}`, matches: values[0] === values[1] });
      }
    }
    return results;
  });
  expect(results).toHaveLength(30);
  for (const result of results) expect(result.matches, result.id).toBe(true);
});
